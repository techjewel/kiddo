/* Writes src/fonts.css: the four typefaces kiddo.page used to fetch
   from Google Fonts, now served from our own origin out of the
   @fontsource packages. Same families and weights as the old
   <link>, woff2 only (every Safari since 12 reads it), and only the
   scripts the app writes in. Each face carries its unicode-range, so a
   browser fetches the Bangla file only for a Bangla page, as Google's
   CSS did. Run again after changing FACES; the output is committed. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const nm = (p) => fileURLToPath(new URL(`../node_modules/@fontsource/${p}`, import.meta.url));

const FACES = [
  { pkg: 'baloo-2', family: 'Baloo 2', weights: [600, 800], subsets: ['latin', 'latin-ext'] },
  { pkg: 'baloo-da-2', family: 'Baloo Da 2', weights: [600, 800], subsets: ['bengali', 'latin', 'latin-ext'] },
  { pkg: 'baloo-bhaijaan-2', family: 'Baloo Bhaijaan 2', weights: [600, 800], subsets: ['arabic', 'latin', 'latin-ext'] },
  { pkg: 'andika', family: 'Andika', weights: [400, 700], subsets: ['latin', 'latin-ext'] },
];

let css = '/* Generated by scripts/make-fonts-css.mjs. Do not edit by hand. */\n';
for (const f of FACES) {
  const ranges = JSON.parse(readFileSync(nm(`${f.pkg}/unicode.json`), 'utf8'));
  for (const w of f.weights) {
    for (const s of f.subsets) {
      css += `@font-face {
  font-family: '${f.family}';
  font-style: normal;
  font-weight: ${w};
  font-display: swap;
  src: url('../node_modules/@fontsource/${f.pkg}/files/${f.pkg}-${s}-${w}-normal.woff2') format('woff2');
  unicode-range: ${ranges[s]};
}
`;
    }
  }
}
writeFileSync(fileURLToPath(new URL('../src/fonts.css', import.meta.url)), css);
console.log('fonts.css written');
